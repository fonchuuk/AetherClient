package core

// BuildID — номер сборки, который заполняет компоновщик при компиляции:
//
//	go build -ldflags "-X aetherglass/launcher/core.BuildID=20261018-2230"
//
// Зачем: exe всегда называется одинаково, а сборок выходит много. Без номера
// в самом интерфейсе невозможно понять, какой именно файл сейчас запущен —
// и легко весь вечер тестировать старую копию, думая, что новая.
// Значение по умолчанию «dev» означает запуск из исходников без компоновщика.
// Version — семантическая версия лаунчера. Именно её сравнивают с меткой
// релиза на GitHub, поэтому при каждом выпуске её надо повышать.
const Version = "0.1.5"

var BuildID = "dev"

// BuildVersion возвращает номер сборки, который показывает интерфейс.
// Пустое значение не выводится: лучше показать ничего, чем пустышку.
func BuildVersion() string {
	if BuildID == "" {
		return ""
	}
	return BuildID
}
